    @Test
    public void testOrm() throws SQLException {
        Connection connection = DriverManager.getConnection("jdbc:mysql:///atguigu", "root", "");

        PreparedStatement preparedStatement = connection.prepareStatement("SELECT emp_id, emp_name, emp_salary, emp_age FROM t_emp WHERE emp_id = ?");

        preparedStatement.setInt(1, 1);

        ResultSet resultSet = preparedStatement.executeQuery();

        /*
         * 先声明变量 employee，并初始化为 null，用来存放查询结果。
         * 如果 resultSet.next() 返回 true，说明查到了数据，再创建 Employee 对象。
         * 如果查不到数据，if 不执行，employee 保持为 null，打印时会输出 null，不会报错。
         *
         * 【赋 null】：避免局部变量可能未初始化导致的编译错误。
         * 【不提前 new】：避免查不到数据时，仍然得到一个各属性都是默认值的空对象。
         *
         * 整体作用：将数据库中的一行记录转换成一个 Java 对象，
         * 这种做法叫 ORM 映射（对象关系映射）的雏形。
         */
        Employee employee = null;

        /*
         * 用 while 时，如果有多行数据，后一行会覆盖前一行，最后只保留最后一行。
         * 如果要查询多行，应该改用 List<Employee>，每次循环都 new 一个对象并 add 到集合中。
         */
        if (resultSet.next()) {
            employee = new Employee();

            int empId = resultSet.getInt("emp_id");
            String empName = resultSet.getString("emp_name");
            double empSalary = resultSet.getDouble("emp_salary");
            int empAge = resultSet.getInt("emp_age");

            // 为对象的属性赋值
            employee.setEmpId(empId);
            employee.setEmpName(empName);
            employee.setEmpSalary(empSalary);
            employee.setEmpAge(empAge);

//            employee = new Employee(empId, empName, empSalary, empAge);
        }

        // 查不到数据时，employee 为 null，会打印 null，不会报错。
        System.out.println(employee);

        resultSet.close();
        preparedStatement.close();
        connection.close();
    }

    @Test
    public void testOrmList() throws SQLException {
        Connection connection = DriverManager.getConnection("jdbc:mysql:///atguigu", "root", "");

        PreparedStatement preparedStatement = connection.prepareStatement("SELECT emp_id, emp_name, emp_salary, emp_age FROM t_emp");

        ResultSet resultSet = preparedStatement.executeQuery();

        Employee employee = null;

        /*
         * List<Employee>：用于存储多个 Employee 对象。
         * 查询结果可能有多行，每行封装成一个 Employee 对象，
         * 使用 List 集合统一保存，方便后续遍历、查询和处理所有对象。
         */
        List<Employee> employeeList = new ArrayList<>();

        while (resultSet.next()) {
            employee = new Employee();

            int empId = resultSet.getInt("emp_id");
            String empName = resultSet.getString("emp_name");
            double empSalary = resultSet.getDouble("emp_salary");
            int empAge = resultSet.getInt("emp_age");

            employee.setEmpId(empId);
            employee.setEmpName(empName);
            employee.setEmpSalary(empSalary);
            employee.setEmpAge(empAge);

            // 将每次循环封装的一行数据的对象存储在集合里
            employeeList.add(employee);
        }

        // 处理结果，遍历集合，逐个获取并处理封装好的 Employee 对象
        for (Employee emp : employeeList) {
            System.out.println(emp);
        }

        resultSet.close();
        preparedStatement.close();
        connection.close();
    }

    @Test
    public void testReturnPK() throws SQLException {
        // 获取数据库连接
        Connection connection = DriverManager.getConnection("jdbc:mysql:///atguigu", "root", "");

        // 预编译SQL语句，告知preparedStatement，返回新增数据的主键列的值
        String sql = "INSERT INTO t_emp(emp_name,emp_salary,emp_age) VALUES (?,?,?)";
        /*
         * PreparedStatement prepareStatement(String sql)
         *   只预编译 SQL，执行后拿不到数据库自动生成的主键。
         * PreparedStatement prepareStatement(String sql, int autoGeneratedKeys)
         *   Statement.RETURN_GENERATED_KEYS 表示执行后要返回自增主键；
         *   Statement.NO_GENERATED_KEYS 表示不需要返回。
         * 只有 INSERT 后想知道新记录的 id 时，才需要用第二种。
         */
        PreparedStatement preparedStatement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);

        // 创建对象，将对象的属性值，填充在?占位符上 （ORM）
        Employee employee = new Employee(null, "Jack", 123.45, 29);
        preparedStatement.setString(1, employee.getEmpName());
        preparedStatement.setDouble(2, employee.getEmpSalary());
        preparedStatement.setInt(3, employee.getEmpAge());

        // 执行SQL，并获取返回的结果
        int result = preparedStatement.executeUpdate();

        /*
         * getGeneratedKeys() 放在 if 里面，是因为插入成功才有主键可取，插入失败去取就没有意义。
         * 规范写法是 try-with-resources：在 if 里面写
         *   try (ResultSet rs = preparedStatement.getGeneratedKeys()) { ... }
         */
        ResultSet resultSet = null;
        // 处理结果
        if (result > 0) {
            System.out.println("成功");

            // 获取当前新增数据的主键列，回显到Java中employee对象的empId属性上。
            // 返回的主键值，是一个单行单列的结果存储在ResultSet里
            /*
             * 签名：ResultSet getGeneratedKeys() throws SQLException。
             * 作用：取出刚才 INSERT 时数据库自动生成的主键。
             * 返回 ResultSet，是因为一次批量插入可能生成多条主键，所以 JDBC 统一用"结果表"的形式返回。
             * 如果去掉 RETURN_GENERATED_KEYS 只调用这个方法，MySQL 驱动会抛 SQLException。
             */
            resultSet = preparedStatement.getGeneratedKeys();
            if (resultSet.next()) {
                /*
                 * 两个重载：int getInt(int columnIndex) 和 int getInt(String columnLabel)。
                 * columnIndex：列索引（通过位置获取）；columnLabel：列标签（通过名称获取）
                 *
                 * 1 指的是 ResultSet 当前行的第 1 列，和 Employee 构造器的参数顺序无关。
                 * getGeneratedKeys 的结果只有一列（主键），所以只能写 1；写 2 会因列不存在而抛异常，
                 * 不会取到 name。
                 * 可以把 ResultSet 看成一张表：next() 负责竖着往下移动到某一行，
                 * getXxx(列号) 负责在当前这一行里横着取某一列。
                 * 循环中每次 next() 之后，当前行已经变成下一行，所以 getInt(1) 取的是新一行的第 1 列，
                 * 不会一直是第一行。
                 *
                 * MySQL 驱动返回的主键列名通常是 "GENERATED_KEY"，不是 "emp_id"，
                 * 而且不同驱动的列名可能不一样。所以取生成的主键时，惯例写 getInt(1)。
                 */
                int empId = resultSet.getInt(1);
                employee.setEmpId(empId);
            }

            System.out.println(employee);
        } else {
            System.out.println("失败");
        }

        // 释放资源
        // Surround With（环绕代码）快捷键：option + cmd + T
        /*
         * resultSet 一开始是 null，只有插入成功时才会被赋值。
         * 插入失败时它仍然是 null，直接调用 close() 会抛 NullPointerException。
         */
        if (resultSet != null) {
            resultSet.close();
        }
        preparedStatement.close();
        connection.close();
    }

    @Test
    public void testMoresInsert() throws SQLException {
        Connection connection = DriverManager.getConnection("jdbc:mysql:///atguigu", "root", "");
        String sql = "INSERT INTO t_emp (emp_name, emp_salary, emp_age) VALUES (?, ?, ?)";
        PreparedStatement preparedStatement = connection.prepareStatement(sql);

        // 获取当前行代码执行的时间。毫秒值
        long start = System.currentTimeMillis();

        for (int i = 0; i < 10000; i++) {
            preparedStatement.setString(1, "Marry" + i);
            preparedStatement.setDouble(2, 100.0 + i);
            preparedStatement.setInt(3, 20 + i);

            /*
             * executeUpdate()：把这条 SQL 发给数据库执行。
             * 签名：int executeUpdate() throws SQLException，返回值是受影响的行数，这里每次是 1。
             * 【前面不写 int update =】
             * 因为 Java 允许忽略方法的返回值。返回值照样存在，只是这里不需要用。
             */
            preparedStatement.executeUpdate();
        }

        long end = System.currentTimeMillis();
        System.out.println(end - start);

        preparedStatement.close();
        connection.close();
    }

    // 测试批处理
    @Test
    public void testBatch() throws SQLException {
        /*
         * 注意：1、必须在连接数据库的URL后面追加?rewriteBatchedStatements=true，允许批量操作
         *      2、新增SQL必须用VALUES。且语句最后不要追加;结束
         *      3、调用addBatch()方法，将SQL语句进行批量添加操作
         *      4、统一执行批量操作，调用executeBatch()
         */

        /*
         * ? 后面是 URL 参数，用来给 MySQL 驱动传配置。
         * rewriteBatchedStatements=true 的意思是“允许驱动改写批量语句”。
         * 不加这个参数时，addBatch() 攒的 10000 条 SQL 会被驱动一条条发送，速度提升不明显。
         * 加上以后，驱动会把它们合并成少量多值 INSERT，例如：
         * INSERT INTO t_emp (...) VALUES (?,?,?),(?,?,?),(?,?,?)...
         */
        Connection connection = DriverManager.getConnection("jdbc:mysql:///atguigu?rewriteBatchedStatements=true", "root", "");

        /*
         * 【不能加分号】
         * 驱动会在末尾拼接 ,(?,?,?)。加了分号会变成 VALUES (?,?,?);,(?,?,?)，SQL 语法错误。
         */
        String sql = "INSERT INTO t_emp (emp_name, emp_salary, emp_age) VALUES (?, ?, ?)";
        PreparedStatement preparedStatement = connection.prepareStatement(sql);

        // 获取当前行代码执行的时间。毫秒值
        long start = System.currentTimeMillis();

        for (int i = 0; i < 10000; i++) {
            // 为占位符赋值
            preparedStatement.setString(1, "Marry" + i);
            preparedStatement.setDouble(2, 100.0 + i);
            preparedStatement.setInt(3, 20 + i);

            /*
             * 签名：void addBatch() throws SQLException。
             * 作用：不立刻执行，而是把当前这组占位符参数存进“批次”。
             * 没有返回值（void），因为这时 SQL 还没执行，自然没有“影响了几行”的结果。
             */
            preparedStatement.addBatch();
        }

        // 执行批量操作
        /*
         * 签名：int[] executeBatch() throws SQLException。
         * 作用：把 addBatch() 攒下的所有参数组一次性发给数据库执行。
         */
        preparedStatement.executeBatch();

        long end = System.currentTimeMillis();
        System.out.println(end - start);

        preparedStatement.close();
        connection.close();
    }
